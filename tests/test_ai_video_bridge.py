import json
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch, MagicMock

from botfarm.ai_video_bridge import hardware, plan, _clips, assemble, comfy_queue
from botfarm.viral_studio import make

class AiVideoBridgeTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory()
        self.root=Path(self.temp.name)
        self.result=make(self.root,'fruit-story','The banana who solved a mystery')
        self.folder=Path(self.result['folder'])
    def tearDown(self):self.temp.cleanup()

    def test_plan_actual_animated_scenes_only_prompts(self):
        result=plan(self.folder)
        data=json.loads(Path(result['shotlist']).read_text())
        self.assertEqual(len(data['shots']),5)
        self.assertIn('same original anthropomorphic strawberry',data['shots'][0]['prompt'])
        self.assertIn('Characters move',data['shots'][0]['prompt'])
        self.assertFalse(result['real_motion_created'])
        self.assertFalse(result['model_auto_installed'])
    def test_no_guilty_video_or_fake_output(self):
        meta_path=self.folder/'metadata.json';meta=json.loads(meta_path.read_text())
        meta['court_verdict']='GUILTY';meta_path.write_text(json.dumps(meta))
        with self.assertRaises(PermissionError):plan(self.folder)
    def test_owner_rights_mandatory(self):
        with self.assertRaises(PermissionError):assemble(self.folder)
    def test_missing_video_clips_is_not_slideshow(self):
        with self.assertRaises((FileNotFoundError,ValueError)):
            assemble(self.folder,rights_confirmed=True)
    def test_hardware_no_unproven_gpu(self):
        report=hardware()
        self.assertEqual(report['real_ai_video_model_installed'],'NOT_VERIFIED')
        self.assertFalse(report['model_auto_installed'])
    def test_comfy_requires_user_exported_workflow(self):
        plan(self.folder)
        with self.assertRaises(ValueError):
            comfy_queue(self.folder,self.folder/'nonexistent.json','42',1)
        workflow=self.folder/'wf.json'
        workflow.write_text(json.dumps({'42':{'inputs':{'text':'old prompt'},'class_type':'CLIPTextEncode'}}))
        class R:
            def __enter__(self):return self
            def __exit__(self,*a):pass
            def read(self,n):return b'{"prompt_id":"demo-queue-id"}'
        with patch('botfarm.ai_video_bridge.urllib.request.urlopen',return_value=R()) as req:
            result=comfy_queue(self.folder,workflow,'42',1)
            self.assertEqual(result['prompt_id'],'demo-queue-id')
            self.assertFalse(result['generation_finished'])
            body=json.loads(req.call_args.args[0].data)
            self.assertIn('camera tracking',body['prompt']['42']['inputs']['text'])
    @unittest.skipUnless(shutil.which('ffmpeg') and shutil.which('ffprobe'),'FFmpeg optional')
    def test_assemble_uses_real_moving_files(self):
        clips=self.folder/'ai_motion_clips';clips.mkdir()
        for i in range(1,6):
            video=clips/f'scene_{i:02d}.mp4'
            # Moving bars generated by a test filter (not claimed to be generative AI)
            proc=subprocess.run(['ffmpeg','-y','-hide_banner','-loglevel','error','-f','lavfi','-i',
                'testsrc2=size=144x256:rate=12','-t','0.7','-c:v','mpeg4','-q:v','7',str(video)],
                capture_output=True,timeout=20)
            self.assertEqual(proc.returncode,0,proc.stderr[-300:])
        result=assemble(self.folder,rights_confirmed=True,width=360)
        self.assertTrue(result['rendered'])
        self.assertEqual(result['real_motion_clips_used'],5)
        self.assertFalse(result['published'])
        self.assertTrue(Path(result['video']).is_file())
        self.assertTrue((self.folder/'AI_MOTION_PROVENANCE.json').exists())
if __name__=='__main__':unittest.main()
